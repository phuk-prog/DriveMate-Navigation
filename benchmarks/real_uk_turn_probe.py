"""Independent UK PUBLIC OSM turn-restriction structural regression probes.

Reads only stripped public OSM XML generated by osmium tags-filter, not user
driving traces. Checks real mapped node-via restrictions against the existing
DMN directed graph + Dijkstra routing. NOT independent road-law verification.
"""
from __future__ import annotations

import argparse
from collections import Counter
from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from engine import RouteNotFound, shortest_route
from map_data import OSMImportError, Provenance, import_osm_xml

ROOT = Path(__file__).resolve().parents[1]
IGNORED = ROOT / "results"
MAX_SOURCE_BYTES = 75_000_000


def _public_input(path: Path) -> bytes:
    target = path.resolve()
    if not target.is_relative_to(IGNORED.resolve()) or target.suffix != ".osm":
        raise ValueError("Public OSM XML must be under ignored results/")
    if not target.is_file() or not 0 < target.stat().st_size <= MAX_SOURCE_BYTES:
        raise ValueError("Missing or oversized public restriction OSM source")
    raw = target.read_bytes()
    if b"<!DOCTYPE" in raw.upper() or b"<!ENTITY" in raw.upper():
        raise ValueError("Do not read XML containing DTD/entities")
    return raw


def _tags(e):
    return {t.attrib["k"]: t.attrib.get("v", "") for t in e.findall("tag")}


def _eligible(rel):
    tags = _tags(rel)
    if tags.get("type") != "restriction":
        return False
    if any("conditional" in name for name in tags):
        return False
    rule = tags.get("restriction:motorcar", tags.get("restriction:motor_vehicle",
                  tags.get("restriction", "")))
    if not (rule.startswith("no_") or rule.startswith("only_")):
        return False
    exemptions = {x.strip() for x in tags.get("except","").replace(",",";").split(";")}
    if "motorcar" in exemptions or "motor_vehicle" in exemptions:
        return False
    members=rel.findall("member")
    roles={role:[m for m in members if m.get("role")==role]
           for role in ("from","via","to")}
    return (len(members)==3 and
            all(len(roles[k])==1 for k in ("from","via","to")) and
            roles["from"][0].get("type")=="way" and
            roles["to"][0].get("type")=="way" and
            roles["via"][0].get("type")=="node")


def _small_subset(rel, ways, nodes):
    members=rel.findall("member")
    wayids=[m.get("ref") for m in members if m.get("type")=="way"]
    selected=[ways.get(wid) for wid in wayids]
    if any(w is None for w in selected):
        return None
    refs={nd.get("ref") for way in selected for nd in way.findall("nd")}
    if None in refs or not refs.issubset(nodes):
        return None
    root=ET.Element("osm", {"version":"0.6"})
    for ref in sorted(refs):
        root.append(deepcopy(nodes[ref]))
    for way in selected:
        root.append(deepcopy(way))
    root.append(deepcopy(rel))
    return ET.tostring(root,encoding="utf-8",xml_declaration=True)


def evaluate(raw: bytes, *, snapshot: str, limit: int=12) -> dict:
    if not 1 <= limit <= 50:
        raise ValueError("Limit must be 1..50")
    if len(raw) > MAX_SOURCE_BYTES or b"<!DOCTYPE" in raw.upper() or b"<!ENTITY" in raw.upper():
        raise ValueError("Unsafe or oversized XML")
    root=ET.fromstring(raw)
    if root.tag != "osm":
        raise ValueError("Expected OSM source")
    for el in root:
        if el.tag in ("node","way","relation") and (
            set(el.attrib) & {"user","uid","changeset"}
        ):
            raise ValueError("Contributor metadata not permitted")
    nodes={el.get("id"):el for el in root.findall("node")}
    ways={el.get("id"):el for el in root.findall("way")}
    relations=root.findall("relation")
    counters=Counter()
    statuses=[]
    for rel in relations:
        counters["relations_seen"] += 1
        if not _eligible(rel):
            counters["unsupported_or_unrelated_relations"] += 1
            continue
        counters["eligible_node_via_relations"] += 1
        sample=_small_subset(rel,ways,nodes)
        if sample is None:
            counters["missing_referenced_objects"] += 1
            continue
        try:
            imported=import_osm_xml(sample, provenance=Provenance(
                "independently selected public UK restriction source",
                snapshot, "Geofabrik-OSM-stripped-public", "© OpenStreetMap contributors"))
        except OSMImportError:
            counters["unsupported_or_incomplete_subgraphs"] += 1
            continue
        graph=imported.graph
        if not graph.prohibited_turns:
            counters["not_applicable_to_imported_car_graph"] += 1
            continue
        tested_pairs=0
        for arriving, leaving in sorted(graph.prohibited_turns):
            first, second=graph.edges[arriving],graph.edges[leaving]
            if first.access!="allowed" or second.access!="allowed":
                counters["inaccessible_car_turn_pairs"] += 1
                continue
            if first.target!=second.source:
                raise AssertionError("Wrong directed restriction adjacency")
            try:
                path=shortest_route(graph,second.source,second.target,
                                    incoming_edge_id=first.edge_id)
            except RouteNotFound:
                counters["safe_no_route_decisions"] += 1
            else:
                previous=first.edge_id
                for eid in path.edge_ids:
                    if (previous,eid) in graph.prohibited_turns:
                        raise AssertionError("Router traversed an OSM-prohibited turn")
                    previous=eid
                if path.edge_ids and path.edge_ids[0]==second.edge_id:
                    raise AssertionError("Forbidden turn recommended as first step")
                counters["alternative_legal_paths_in_partial_graph"] += 1
            tested_pairs+=1
        if tested_pairs:
            counters["judged_osm_rule_cases"] += 1
            counters["tested_osm_rule_pairs"] += tested_pairs
            statuses.append("OSM-rule-adherence")
        if len(statuses) >= limit:
            break
    result={
        "classification":"real-public-uk-osm-rule-adherence-not-independent-legality",
        "source_snapshot":snapshot,"source_sha256":sha256(raw).hexdigest(),
        "case_limit":limit,
        "source_relations_seen":counters["relations_seen"],
        "eligible_node_via_relations":counters["eligible_node_via_relations"],
        "cases_with_judged_map_rule":counters["judged_osm_rule_cases"],
        "tested_map_rule_pairs":counters["tested_osm_rule_pairs"],
        "alternative_legal_paths_in_partial_graph":counters["alternative_legal_paths_in_partial_graph"],
        "safe_no_route_decisions":counters["safe_no_route_decisions"],
        "unsupported_or_incomplete_count":(
            counters["unsupported_or_unrelated_relations"]+
            counters["missing_referenced_objects"]+
            counters["unsupported_or_incomplete_subgraphs"]+
            counters["not_applicable_to_imported_car_graph"]),
        "independent_road_legality_verified":False,
        "true_vehicle_gps_tested":False,
        "external_engines_executed":0,
        "navigation_score":None,
        "warning":"OSM relation interpretation and route non-use only, not a signed legal-turn or live-driving proof."
    }
    if not result["cases_with_judged_map_rule"]:
        result["coverage_gap"]="No supported motorcar node-via turn relation exercised in public source"
    return result


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--input",required=True,type=Path)
    p.add_argument("--snapshot",required=True)
    p.add_argument("--limit",type=int,default=12)
    args=p.parse_args()
    print(json.dumps(evaluate(_public_input(args.input),
                   snapshot=args.snapshot,limit=args.limit),indent=2))

if __name__=="__main__":
    main()
